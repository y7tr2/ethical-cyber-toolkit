#!/usr/bin/env python3\n# Read JSON safely — Monitoring\n# قراءة JSON بأمان — المراقبة والتنبيه\n# استخدمه فقط على جهازك أو على نظام لديك إذن كتابي لاختباره. لا تجمع كلمات مرور أو بيانات شخصية.\n\n"""Monitoring: parse known JSON fields and ignore unknown input."""
import json

raw = '{"check": "monitoring-174", "status": "review", "extra": "ignored"}'
record = json.loads(raw)
safe_view = {"check": str(record.get("check", "")), "status": str(record.get("status", ""))}
